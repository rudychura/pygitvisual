public class Suma {
    public static int sumar(int a, int b) {
        return a + b;
    }

    public static void main(String[] args) {
        int numero1 = 7;
        int numero2 = 5;
        int resultado = sumar(numero1, numero2);
        System.out.println(numero1 + " + " + numero2 + " = " + resultado);
    }
}
